CREATE TABLE STUDENTS (
  student_id   NUMBER PRIMARY KEY,
  student_name VARCHAR2(80) NOT NULL,
  course_name  VARCHAR2(50) NOT NULL,
  total_fees   NUMBER(10,2) NOT NULL CHECK (total_fees > 0),
  paid_fees    NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (paid_fees >= 0),
  pending_fees NUMBER(10,2)
    GENERATED ALWAYS AS (total_fees - paid_fees) VIRTUAL,
  CONSTRAINT chk_paid_total CHECK (paid_fees <= total_fees)
);

CREATE TABLE FEE_PAYMENTS (
  payment_id      NUMBER PRIMARY KEY,
  student_id      NUMBER NOT NULL REFERENCES STUDENTS(student_id),
  payment_amount  NUMBER(10,2) NOT NULL CHECK (payment_amount > 0),
  payment_date    DATE DEFAULT SYSDATE NOT NULL,
  payment_mode    VARCHAR2(20) NOT NULL
);

CREATE TABLE FEE_AUDIT (
  audit_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id       NUMBER NOT NULL,
  old_paid_fees    NUMBER(10,2),
  new_paid_fees    NUMBER(10,2),
  old_pending_fees NUMBER(10,2),
  new_pending_fees NUMBER(10,2),
  change_date      DATE DEFAULT SYSDATE NOT NULL
);
